    parser.add_argument("--external-snapshot", type=Path, default=None)
    parser.add_argument("--reviews", type=Path, default=None)
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument("--max-questions", type=int, default=240)
    parser.add_argument("--external-questions", type=int, default=40)
