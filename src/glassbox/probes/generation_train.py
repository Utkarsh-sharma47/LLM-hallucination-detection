def _check_model_width(loaded, row: dict[str, object]) -> None:
    config = getattr(loaded.model, "config", None)
    hidden_size = getattr(config, "hidden_size", None)
    layer_count = getattr(config, "num_hidden_layers", None)
    if hidden_size is not None and int(row["feature_dim"]) != int(hidden_size):
        raise RuntimeError(
            f"Feature width {row['feature_dim']} does not match model hidden size {hidden_size}"
        )
    if (
        layer_count is not None
        and row.get("hidden_state_count") is not None
        and int(row["hidden_state_count"]) != int(layer_count) + 1
    ):
        raise RuntimeError(
            "Hidden-state count does not match the embedding stream plus transformer layers"
        )


